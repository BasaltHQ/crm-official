// Rebuild the self-contained, lazy-loaded Three runtime from an installed Three r184.
// Runtime files are mirrored with the landing components; sites need no new dependency.
const fs = require('node:fs');
const path = require('node:path');
const esbuild = require('esbuild');
const threeRoot = process.env.BASALT_THREE_SOURCE || 'U:/BasaltHQ/main-site/node_modules/three';
const version = JSON.parse(fs.readFileSync(path.join(threeRoot, 'package.json'), 'utf8')).version;
if (version !== '0.184.0') throw new Error(`Expected Three 0.184.0; found ${version}`);
const output = path.resolve(__dirname, '../components/basalt-marketing');
esbuild.buildSync({
    stdin: { contents: `export * as THREE from 'three';
export {RoomEnvironment} from 'three/addons/environments/RoomEnvironment.js';
export {RoundedBoxGeometry} from 'three/addons/geometries/RoundedBoxGeometry.js';
export {EffectComposer} from 'three/addons/postprocessing/EffectComposer.js';
export {RenderPass} from 'three/addons/postprocessing/RenderPass.js';
export {SSAOPass} from 'three/addons/postprocessing/SSAOPass.js';
export {UnrealBloomPass} from 'three/addons/postprocessing/UnrealBloomPass.js';
export {OutputPass} from 'three/addons/postprocessing/OutputPass.js';
export {ShaderPass} from 'three/addons/postprocessing/ShaderPass.js';
export {FXAAShader} from 'three/addons/shaders/FXAAShader.js';`, resolveDir: path.dirname(threeRoot) },
    bundle: true, format: 'esm', platform: 'browser', target: 'es2020', minify: true,
    outfile: path.join(output, 'three-runtime.js'),
    banner: { js: '/* eslint-disable */\n/* Three.js 0.184.0 · MIT · see THREE-LICENSE.txt. Generated by scripts/build-basalt-3d.cjs. */' },
});
fs.copyFileSync(path.join(threeRoot, 'LICENSE'), path.join(output, 'THREE-LICENSE.txt'));
console.log('Three r184 runtime and MIT license built.');
